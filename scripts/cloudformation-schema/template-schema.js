const { pointerSegmentOf, resourceTypeDefinitionOf } = require('./provider-schemas');
const { templateSectionsOf } = require('./template-sections');

const SCHEMA_DIALECT = 'https://json-schema.org/draft/2020-12/schema';

function templateSchemaOf(providerSchemas, { region, downloadDate }) {
  const leftOutPatterns = [];
  const typeDefinitions = {};
  const resourceTypes = [...providerSchemas]
    .sort((left, right) => left.typeName.localeCompare(right.typeName))
    .map((provider) => {
      const definition = resourceTypeDefinitionOf(provider, leftOutPatterns);
      typeDefinitions[provider.typeName] = definition;
      return {
        typeName: provider.typeName,
        pointer: `#/$defs/${pointerSegmentOf(provider.typeName)}`,
        propertiesRequired: Array.isArray(definition.required),
      };
    });
  const { sections, definitions, functions } = templateSectionsOf(resourceTypes);
  const schema = {
    $schema: SCHEMA_DIALECT,
    $comment: 'Generated by scripts/cloudformation-schema from the CloudFormation resource provider schemas '
      + `of ${region}, downloaded ${downloadDate}.`,
    description: 'An AWS CloudFormation template.',
    type: 'object',
    required: ['Resources'],
    additionalProperties: false,
    'x-yaml-dsl-functions': functions,
    properties: sections,
    $defs: { ...definitions, ...typeDefinitions },
  };
  return { schema, leftOutPatterns };
}

module.exports = { templateSchemaOf };
